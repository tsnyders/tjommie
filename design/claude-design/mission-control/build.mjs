// Mission Control build: tokens.json -> tokens.css, a contrast check of every text and glyph pair, the light copy of the
// desktop chat screen, and the icon and avatar sprites each HTML file uses (so every file stays self-contained).
// Usage: node build.mjs [--shots [name-filter]]   (exits 1 when a contrast pair fails)
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { join, dirname, basename } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { execFileSync } from "node:child_process";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..", "..", "..");
const T = JSON.parse(readFileSync(join(here, "tokens.json"), "utf8"));

// 1. tokens.css
const px = (n) => (n === 0 ? "0" : `${n}px`);
const font = (t) => `${t.weight} ${T.font[t.font].stretch} ${t.size}px/${t.line}px ${T.font[t.font].css}`;
const shadow = (list) => list.map((s) => `${s.x}px ${s.y}px ${s.blur}px ${s.spread}px ${s.color}`).join(", ");
const root = [
  ...Object.entries(T.font).map(([k, f]) => `--font-${k}: ${f.css};`),
  ...Object.entries(T.type.desktop).map(([k, t]) => `--t-${k}: ${font(t)};`),
  ...Object.entries(T.type.phone).map(([k, t]) => `--tp-${k}: ${font(t)};`),
  ...Object.entries(T.space).map(([k, v]) => `--space-${k}: ${px(v)};`),
  ...Object.entries(T.radius).map(([k, v]) => `--r-${k}: ${px(v)};`),
  ...Object.entries(T.size).map(([k, v]) => `--size-${k}: ${px(v)};`),
  ...Object.entries(T.motion.duration).map(([k, v]) => `--dur-${k}: ${v}ms;`),
  ...Object.entries(T.motion.easing).map(([k, v]) => `--ease-${k}: ${v};`),
];
const theme = (name) => [
  `color-scheme: ${name};`,
  ...Object.entries(T.color[name]).map(([k, v]) => `--${k}: ${v};`),
  ...Object.entries(T.bot).map(([k, v]) => `--bot-${k}: ${v[name]};`),
  ...Object.entries(T.elevation[name]).map(([k, v]) => `--shadow-${k}: ${shadow(v)};`),
];
const block = (selector, lines) => `${selector} {\n${lines.map((l) => `  ${l}`).join("\n")}\n}\n`;
writeFileSync(
  join(here, "tokens.css"),
  `/* Generated by build.mjs from tokens.json. Edit tokens.json, then run: node build.mjs */\n` +
    block(":root", root) +
    block(':root, [data-theme="dark"]', theme("dark")) +
    block('[data-theme="light"]', theme("light")) +
    `@media (prefers-reduced-motion: reduce) {\n  :root { --dur-fast: 0ms; --dur-base: 0ms; --dur-slow: 0ms; }\n}\n`,
);

// 2. Contrast (WCAG 2.x relative luminance). Body text 4.5:1, glyphs, lamps and the focus ring 3:1.
const lum = (hex) =>
  [1, 3, 5]
    .map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4))
    .reduce((sum, c, i) => sum + c * [0.2126, 0.7152, 0.0722][i], 0);
const ratio = (a, b) => {
  const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};
const failures = [];
for (const name of ["dark", "light"]) {
  const c = { ...T.color[name], ...Object.fromEntries(Object.entries(T.bot).map(([k, v]) => [`bot-${k}`, v[name]])) };
  const need = (fg, bg, min) => {
    const r = ratio(c[fg], c[bg]);
    if (r < min) failures.push(`${name}: ${fg} on ${bg} = ${r.toFixed(2)} (needs ${min})`);
  };
  const grounds = ["bg", "surface", "raised", "select", "chrome", "sunken"];
  for (const t of ["text", "text-2", "text-3"]) for (const g of grounds) need(t, g, 4.5);
  for (const s of ["needs", "working", "limited", "paused", "setup", "idle", "danger"]) for (const g of ["bg", "surface", "raised", "select"]) need(s, g, 4.5);
  for (const s of ["working", "limited", "paused", "setup", "danger"]) need(s, `${s}-tint`, 4.5);
  need("needs", "needs-tint", 4.5);
  need("needs-on", "needs-solid", 4.5);
  for (const s of ["needs", "working", "limited", "paused", "setup", "danger"]) {
    need(`${s}-on`, `${s}-solid`, 3);
    // A yellow lamp can't reach 3:1 on paper, so Needs you lamps, badges and pills carry a darker edge.
    for (const g of ["bg", "surface", "chrome", "raised"]) need(s === "needs" ? "needs-edge" : `${s}-solid`, g, 3);
  }
  need("on-primary", "primary", 4.5);
  for (const g of ["bg", "surface", "chrome", "raised"]) need("focus", g, 3);
  for (const g of ["bg", "surface", "chrome"]) need("live", g, 3);
  for (const k of ["code-text", "code-keyword", "code-fn", "code-literal", "code-comment"]) need(k, "sunken", 4.5);
  for (const b of Object.keys(T.bot)) for (const g of ["bg", "surface", "raised", "select", "chrome"]) need(`bot-${b}`, g, 3);
}

// 3. Sprites: Lucide symbols from the installed lucide-react, avatar symbols from the app's own bot-avatar.tsx paths.
const lucide = join(repo, "node_modules", "lucide-react", "dist", "esm", "icons");
function iconSymbol(name, file = name) {
  const src = readFileSync(join(lucide, `${file}.mjs`), "utf8");
  const alias = src.match(/export \{ default \} from '\.\/([\w-]+)\.mjs'/); // renamed icons re-export their new name
  if (alias) return iconSymbol(name, alias[1]);
  const data = src.match(/const __iconData = (\{[\s\S]*?\n\});/);
  if (!data) throw new Error(`Lucide icon not found: ${name}`);
  const node = Function(`return ${data[1]}`)().node;
  const body = node.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => `${k}="${v}"`).join(" ")}/>`).join("");
  return `<symbol id="i-${name}" viewBox="0 0 24 24">${body}</symbol>`;
}
const avatarSource = readFileSync(join(repo, "packages", "ui", "components", "bot-avatar.tsx"), "utf8");
const shapes = Object.fromEntries([...avatarSource.matchAll(/"?([\w-]+)"?: \{\s*body: "([^"]+)",\s*eyes: "([^"]+)",?\s*\}/g)].map(([, k, body, eyes]) => [k, { body, eyes }]));
if (Object.keys(shapes).length !== 8) throw new Error(`Expected 8 avatar shapes, found ${Object.keys(shapes).length}`);
const avatarSymbol = (name) =>
  `<symbol id="a-${name}" viewBox="0 0 40 40"><path d="${shapes[name].body}" style="fill:currentColor"/><path d="${shapes[name].eyes}" style="fill:none;stroke:var(--bot-eye);stroke-width:3;stroke-linecap:round"/></symbol>`;

const SPRITE = /<!--sprite-->[\s\S]*?<!--\/sprite-->/;
const dirs = ["components", "screens"].map((d) => join(here, d));
const chat = join(here, "screens", "desktop-chat.html");
writeFileSync(
  join(here, "screens", "desktop-chat-alt.html"),
  readFileSync(chat, "utf8")
    .replace('<html lang="en" data-theme="dark">', '<html lang="en" data-theme="light">')
    .replace(/<title>[^<]*<\/title>/, "<title>Mission Control: desktop chat, light theme</title>"),
);
const files = dirs.flatMap((d) => readdirSync(d).filter((f) => f.endsWith(".html")).map((f) => join(d, f)));
for (const file of files) {
  const html = readFileSync(file, "utf8");
  if (!SPRITE.test(html)) throw new Error(`No <!--sprite--><!--/sprite--> marker in ${basename(file)}`);
  const content = html.replace(SPRITE, "");
  const icons = [...new Set([...content.matchAll(/#i-([a-z0-9-]+)/g)].map((m) => m[1]))].sort();
  const avatars = [...new Set([...content.matchAll(/#a-([a-z-]+)/g)].map((m) => m[1]))].sort();
  const sprite = `<!--sprite--><svg width="0" height="0" style="position:absolute" aria-hidden="true">${[...icons.map((n) => iconSymbol(n)), ...avatars.map(avatarSymbol)].join("")}</svg><!--/sprite-->`;
  writeFileSync(file, html.replace(SPRITE, sprite));
}

// 4. Screenshots with headless Edge: desktop screens at 1x, phone screens at 2x, component sheets at their <meta name="shot">.
if (process.argv.includes("--shots")) {
  const filter = process.argv[process.argv.indexOf("--shots") + 1] ?? "";
  const edge = "C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe";
  mkdirSync(join(here, "shots", "components"), { recursive: true });
  for (const file of files.filter((f) => basename(f).includes(filter))) {
    const name = basename(file, ".html");
    const component = file.includes(`${join("components", "")}`);
    const phone = name.startsWith("phone-");
    const meta = readFileSync(file, "utf8").match(/<meta name="shot" content="(\d+)x(\d+)">/);
    const [w, h] = component ? (meta ? [meta[1], meta[2]] : [1280, 1000]) : phone ? [412, 892] : [1440, 900];
    const out = join(here, "shots", component ? "components" : "", `${name}.png`);
    execFileSync(edge, ["--headless=new", "--disable-gpu", "--hide-scrollbars", "--virtual-time-budget=5000", `--window-size=${w},${h}`, `--force-device-scale-factor=${phone ? 2 : 1}`, `--screenshot=${out}`, pathToFileURL(file).href], { stdio: "ignore" });
    console.log(`shot ${out}`);
  }
}

if (failures.length) {
  console.error(`Contrast failures:\n${failures.join("\n")}`);
  process.exitCode = 1;
} else console.log("tokens.css written; all contrast pairs pass.");
